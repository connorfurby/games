import { expect, test } from '@playwright/test'

/** 2.0 shell: HUD, Next-goal tag, hubs, store scene, inbox drawer, phone layout. */
test('2.0 shell boots into the store with a next goal', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (e) => errors.push(e.message))
  await page.goto('/play/grocery-empire/dev')
  await page.getByTitle('Saves, settings and tools').click()
  await page.locator('.ge-dev-stage', { hasText: 'Era 2' }).first().click()
  await page.keyboard.press('Escape')
  await expect(page.locator('.g2-tools')).toHaveCount(0)
  await expect(page.locator('.g2-goal')).toBeVisible()
  await expect(page.locator('.g2-hub', { hasText: 'Store' })).toBeVisible()
  await page.locator('.g2-hub', { hasText: 'Store' }).click()
  await expect(page.locator('.sc-scene .sc-svg')).toBeVisible()
  await expect(page.locator('.sc-scene .sc-live')).toHaveCount(1)
  await page.keyboard.press('m')
  await expect(page.locator('.g2-inbox')).toBeVisible()
  await page.keyboard.press('m')
  await expect(page.locator('.g2-inbox')).toHaveCount(0)
  await page.locator('.g2-hub', { hasText: 'Empire' }).click()
  await page.locator('.g2-main .g2-subtab', { hasText: 'Upgrades' }).click()
  await expect(page.locator('.st-node').first()).toBeVisible()
  expect(errors).toEqual([])
})

test.describe('phone', () => {
  test.use({ viewport: { width: 390, height: 844 } })
  test('Unpack is reachable and hubs sit at the bottom', async ({ page }) => {
    await page.goto('/play/grocery-empire/dev')
    await page.getByTitle('Saves, settings and tools').click()
    await page.locator('.ge-dev-stage', { hasText: 'Era 1' }).first().click()
    await page.keyboard.press('Escape')
    await page.locator('.g2-hub', { hasText: 'Store' }).click()
    // On phones Unpack is docked above the hub bar, visible without scrolling.
    const unpack = page.locator('.fl-dock .ge-unpack')
    await expect(unpack).toBeInViewport()
    await unpack.click()
    const hubs = await page.locator('.g2-hubs').boundingBox()
    expect(hubs!.y).toBeGreaterThan(700)
  })

  test('sub-tabs are tappable: Rivals and the Empire Map open', async ({ page }) => {
    await page.goto('/play/grocery-empire/dev')
    await page.getByTitle('Saves, settings and tools').click()
    await page.locator('.ge-dev-stage', { hasText: 'Era 3' }).first().click()
    await page.keyboard.press('Escape')
    await page.locator('.g2-hub', { hasText: 'Team' }).click()
    const rivals = page.locator('.g2-subtab', { hasText: 'Rivals' })
    const box = await rivals.boundingBox()
    expect(box!.height).toBeGreaterThan(20)
    await rivals.click()
    await expect(page.locator('.rv-card', { hasText: 'Penny Pantry' })).toBeVisible()
    await page.locator('.g2-hub', { hasText: 'Empire' }).click()
    await page.locator('.g2-subtab', { hasText: 'Map' }).click()
    await expect(page.locator('.mp-svg')).toBeVisible()
    await page.locator('.mp-pin--store').first().dispatchEvent('click')
    await expect(page.locator('.mp-detail h3')).not.toHaveText('The flagship')
  })
})

test('Menu drawer holds settings, saves and links', async ({ page }) => {
  await page.goto('/play/grocery-empire/dev')
  await page.getByTitle('Saves, settings and tools').click()
  const drawer = page.locator('.g2-tools')
  await expect(drawer).toBeVisible()
  await expect(drawer.locator('.dv-stage').first()).toBeVisible()
  await drawer.locator('.g2-subtab', { hasText: 'Settings' }).click()
  await expect(drawer.getByText('Reduced motion')).toBeVisible()
  await drawer.locator('.g2-subtab', { hasText: 'Go' }).click()
  await expect(drawer.getByRole('link', { name: /Guide/ })).toBeVisible()
  await page.locator('.g2-scrim').click({ position: { x: 10, y: 400 } })
  await expect(drawer).toHaveCount(0)
})

test('Museum: chest opens to a relic that lands on the wall', async ({ page }) => {
  await page.goto('/play/grocery-empire/dev')
  await page.getByTitle('Saves, settings and tools').click()
  await page.locator('.dv-btn', { hasText: 'Reset museum' }).click()
  await page.locator('.ge-dev-stage', { hasText: 'Era 2' }).first().click()
  await page.locator('.dv-btn', { hasText: '+1 chest each rarity' }).click()
  await page.keyboard.press('Escape')
  await page.locator('.g2-hub', { hasText: 'Museum' }).click()
  await expect(page.locator('.mu-tile.is-unknown').first()).toBeVisible()
  await page.locator('.mu-chest--common').click()
  for (let i = 0; i < 3; i++) await page.locator('.co-chest').click({ force: true })
  await expect(page.locator('.co-card')).toBeVisible()
  const name = (await page.locator('.co-card__name').textContent())!.trim()
  await page.keyboard.press('Escape')
  await expect(page.locator('.co')).toHaveCount(0)
  await expect(page.locator('.mu-tile', { hasText: name })).toBeVisible()
})
