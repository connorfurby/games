function slug(s: string): string {
  return s
    .toLowerCase()
    .replace(/’/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
}

export const RELICS: RelicDef[] = [
  ...(Object.entries(CHEST_WINGS) as [Exclude<WingId, 'oddities'>, Row[]][]).flatMap(([wing, rows]) =>
    rows.map(([name, glyph, flavor], i) => ({
      id: `${wing}:${slug(name)}`,
      name,
      wing,
      rarity: LADDER[i]!,
      glyph,
      flavor,
    })),
  ),
  ...ODDITIES.map(([name, glyph, flavor, rarity, feat]) => ({
    id: `oddities:${slug(name)}`,
    name,
    wing: 'oddities' as const,
    rarity,
    glyph,
    flavor,
    feat,
  })),
]

export const RELIC_BY_ID: Record<string, RelicDef> = Object.fromEntries(RELICS.map((r) => [r.id, r]))

export function relicsInWing(wing: WingId): RelicDef[] {
  return RELICS.filter((r) => r.wing === wing)
}

/** Stable small number per relic, for icon variation. */
export function relicSeed(id: string): number {
  let h = 2166136261
  for (let i = 0; i < id.length; i++) {
    h ^= id.charCodeAt(i)
    h = Math.imul(h, 16777619)
  }
  return h >>> 0
}
